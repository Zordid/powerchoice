VID      EQU 10H
INICOUNT EQU 3*60*18
CGAPORT  EQU 03D8H
MGAPORT  EQU 03B8H
MGAMODE  EQU 7
TRUE     EQU 1
FALSE    EQU 0

;

DOS   MACRO FUNC
      MOV AH,FUNC
      INT 21H
      ENDM

LINK  MACRO INT,OLDINTLOC,NEWINTLOC
      MOV AL,INT
      DOS 35H
      MOV WORD PTR OLDINTLOC,BX
      MOV WORD PTR OLDINTLOC+2,ES
      MOV DX,OFFSET NEWINTLOC
      MOV AL,INT
      DOS 25H
      ENDM

;

CODE SEGMENT
ASSUME CS:CODE,DS:CODE
ORG 100H

START:  JMP INIT

OLDINT09 DD ?
OLDINT0B DD ?
OLDINT0C DD ?
OLDINT1C DD ?
ENABLED  DB TRUE
EVENT    DB FALSE
COUNT    DW INICOUNT
TABLE    DB 2CH,28H,2DH,29H
         DB 2AH,2EH,1EH,29H

INT09   PROC FAR
        MOV CS:[EVENT],TRUE
        JMP CS:[OLDINT09]
INT09   ENDP

INT0B   PROC FAR
        MOV CS:[EVENT],TRUE
        JMP CS:[OLDINT0B]
INT0B   ENDP

INT0C   PROC FAR
        MOV CS:[EVENT],TRUE
        JMP CS:[OLDINT0C]
INT0C   ENDP

;

GETMOD  PROC NEAR
        MOV AH,0FH
        INT VID
        MOV DX,CGAPORT
        CMP AL,MGAMODE
        JNE GETMOD1
        MOV DX,MGAPORT
GETMOD1:MOV BL,AL
        XOR BH,BH
        MOV AL,CS:[TABLE+BX]
        RET
GETMOD  ENDP

;

INT1C   PROC FAR
        PUSH AX
        PUSH BX
        PUSH DX
        DEC CS:[COUNT]
        JNE L01
        MOV CS:[COUNT],INICOUNT
        MOV CS:[ENABLED],FALSE
        CALL GETMOD
        AND AL,0F7H
        OUT DX,AL
L01:    TEST CS:[EVENT],TRUE
        JE END1C
        MOV CS:[COUNT],INICOUNT
        MOV CS:[EVENT],FALSE
        TEST CS:[ENABLED],TRUE
        JNE END1C
        MOV CS:[ENABLED],TRUE
        CALL GETMOD
        OUT DX,AL
END1C:  POP DX
        POP BX
        POP AX
        JMP CS:[OLDINT1C]
INT1C   ENDP

;

INIT    PROC NEAR
        CLI
        LINK 1CH,OLDINT1C,INT1C
        LINK 09H,OLDINT09,INT09
        LINK 0BH,OLDINT0B,INT0B
        LINK 0CH,OLDINT0C,INT0C
        STI
        MOV DX,OFFSET MSG
        DOS 9
        MOV DX,OFFSET INIT
        INT 27H

MSG     DB 10,13,"MSAVE V1.0"
        DB 13,10,"$"
INIT    ENDP

CODE ENDS
END START
